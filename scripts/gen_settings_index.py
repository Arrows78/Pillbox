#!/usr/bin/env python3
"""Writes Sources/Pillbox/SettingsIndex.swift: the titles the settings search matches, read from the pane sources.

Each pane's card, row and note titles are the string literals in its file, so the index follows the code and needs no
second list. Titles built at run time (formatted, or from a list) are not indexed. Run it after changing a pane;
`--check` fails when the generated file is out of date, and CI runs it.
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
sources = root / "Sources/Pillbox"
OUT = sources / "SettingsIndex.swift"

# Pane raw value -> the file that builds its page.
# A pane can be built in more than one file: the Home settings card lives with the Home layout.
FILES = {
    "general": ["SettingsGeneral.swift"], "island": ["SettingsIsland.swift"], "tabs": ["SettingsTabs.swift", "HomeLayout.swift"],
    "alerts": ["SettingsAlerts.swift"], "audio": ["SettingsAudio.swift"], "windows": ["SettingsWindows.swift"],
    "integrations": ["SettingsIntegrations.swift"], "shortcuts": ["SettingsShortcuts.swift"], "about": ["SettingsAbout.swift"],
    "permissions": ["Permissions.swift"],
}

CARD = re.compile(r'SettingsCard\(title: "([^"]+)"')
TOGGLE = re.compile(r'SettingsToggle\("([^"]+)"')
ROW = re.compile(r'SettingsRow\(title: "([^"]+)"')
PERMISSION = re.compile(r'case \.\w+: localized\("([^"]+)"\)')
PREFERENCE = re.compile(r'Preferences\.(\w+)\.key')

def titles(path, pattern):
    out = []
    for m in pattern.finditer(path.read_text()):
        t = m.group(1)
        if "\\(" in t or "%" in t or t in out:
            continue
        out.append(t)
    return out

def pane_title():
    """The English title of each pane, from the title switch in SettingsKit."""
    text = (sources / "SettingsKit.swift").read_text()
    block = text[text.index("    var title: LocalizedStringKey {"):text.index("    var symbol: String {")]
    return dict(re.findall(r'case \.(\w+): "([^"]+)"', block))

def build():
    titles_of_pane = pane_title()
    lines = [
        "// Generated by scripts/gen_settings_index.py from the settings panes: do not edit by hand.",
        "",
        "extension SettingsPane {",
        "    /// What the search matches for each pane: its title, then the card, row and permission titles in its file.",
        "    static let indexed: [SettingsPane: [String]] = [",
    ]
    counts = {}
    prefs_of = {}
    for pane, filenames in FILES.items():
        found = []
        prefs = []
        for filename in filenames:
            path = sources / filename
            found += titles(path, PERMISSION) if pane == "permissions" else titles(path, CARD) + titles(path, TOGGLE) + titles(path, ROW)
            for name in PREFERENCE.findall(path.read_text()):
                if name not in prefs:
                    prefs.append(name)
        names = [titles_of_pane[pane]] + [t for t in found if t != titles_of_pane[pane]]
        counts[pane] = len(names)
        prefs_of[pane] = prefs
        items = ", ".join('"' + n.replace('"', '\\"') + '"' for n in names)
        lines.append(f"        .{pane}: [{items}],")
    lines += [
        "    ]",
        "",
        "    /// The preferences each pane edits, read from its source: \"Reset this pane\" puts exactly these back to their defaults.",
        "    static let preferenceKeys: [SettingsPane: [String]] = [",
    ]
    for pane in FILES:
        items = ", ".join(f"Preferences.{name}.key" for name in prefs_of[pane])
        lines.append(f"        .{pane}: [{items}],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines), counts

def main():
    text, counts = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("SettingsIndex.swift is out of date: run scripts/gen_settings_index.py")
        print("settings index up to date")
        return
    OUT.write_text(text)
    print("indexed", ", ".join(f"{p} {n}" for p, n in counts.items()))

if __name__ == "__main__":
    main()
